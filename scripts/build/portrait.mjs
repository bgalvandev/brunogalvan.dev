import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

// Builds the portrait out of source code: a block of this repository's own
// TypeScript, laid on a grid, where each character's weight comes from the
// luminance of the photograph. The face is not drawn on top of the code - it
// is what the code's light and dark make. Run by hand (`pnpm run art:generate`).
const root = path.resolve(import.meta.dirname, '../..');
// 78 columns, not more: each row is a run of spans, and below about 8px the
// browser rounds every run's start position independently, so the monospace
// grid drifts and the glyphs overlap. Fewer, larger cells keep it exact.
const COLS = 78;
// Monospace cells are about twice as tall as they are wide.
const CELL_RATIO = 0.5;

// Cropped to the head: the full frame spends half its cells on a blank wall
// and a dark collar, and neither carries any of the likeness.
const CROP = { left: 168, top: 28, width: 470, height: 618 };
const image = sharp(path.join(root, 'src/assets/bruno-galvan.png')).extract(
  CROP,
);
const { width, height } = { width: CROP.width, height: CROP.height };
const rows = Math.round((COLS * CELL_RATIO * height) / width);
// The photograph is a headshot on a light wall: without stretching the
// histogram and steepening it, almost every cell lands in the middle tiers and
// no face appears at all.
const { data } = await image
  .resize(COLS, rows, { fit: 'fill' })
  .grayscale()
  .normalise()
  .linear(1.9, -92)
  .raw()
  .toBuffer({ resolveWithObject: true });

// The source text. Real code, stripped to a continuous stream of glyphs so the
// grid never breaks mid-token in a way that reads as noise.
const sources = await Promise.all(
  ['src/i18n/routes.ts', 'src/modules/home/experience.ts'].map((file) =>
    readFile(path.join(root, file), 'utf8'),
  ),
);
// The wall behind the head is as bright as the face, so on a dark plate the
// background glowed as much as the likeness. A radial falloff keeps the centre
// and lets the edges go to nothing.
function vignette(x, y) {
  const nx = (x / (COLS - 1) - 0.5) * 2;
  const ny = (y / (rows - 1) - 0.56) * 2.05;
  const r = Math.sqrt(nx * nx + ny * ny);
  if (r <= 0.52) return 1;
  if (r >= 1.02) return 0;
  const t = (r - 0.52) / 0.5;
  return 1 - t * t * (3 - 2 * t);
}

const stream = sources
  .join('\n')
  .replace(/\/\/[^\n]*/g, '')
  .replace(/\s+/g, ' ')
  .replace(/[^\x20-\x7e]/g, '')
  .trim();

// Eight tiers, read straight off the luminance: a bright pixel carries a bright
// glyph. The portrait is shown on a dark plate in both themes - it is another
// screen in the same room as the drawing - so one mapping serves both. Reading
// it inverted lit the hair and hollowed out the face.
const TIERS = 8;
// SVG rather than a <pre>: laid out as HTML the rows became dozens of inline
// runs, and the engine rounded each run's origin until the columns drifted and
// the glyphs overlapped. One <text> per row with an explicit textLength pins
// every row to the same width no matter how many runs it is cut into.
const EM = 10;
const ADVANCE = EM * 0.6;
const LINE = EM * 1.18;

const escape = (text) =>
  text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    // Astro reads a bare `{` in markup as an expression, and this is TypeScript.
    .replace(/\{/g, '&#123;')
    .replace(/\}/g, '&#125;');

let cursor = 0;
const rowsOut = [];
for (let y = 0; y < rows; y++) {
  const runs = [];
  let run = { tier: -1, text: '' };
  for (let x = 0; x < COLS; x++) {
    const luma = (data[y * COLS + x] ?? 0) * vignette(x, y);
    const tier = Math.min(TIERS - 1, Math.floor((luma / 256) * TIERS));
    const char = stream[cursor % stream.length] ?? '.';
    cursor += 1;
    if (tier === run.tier) run.text += char;
    else {
      if (run.text) runs.push(run);
      run = { tier, text: char };
    }
  }
  if (run.text) runs.push(run);
  const spans = runs
    .map((r) => `<tspan class="t${r.tier}">${escape(r.text)}</tspan>`)
    .join('');
  rowsOut.push(
    `<text x="0" y="${((y + 1) * LINE).toFixed(1)}" textLength="${(COLS * ADVANCE).toFixed(1)}" lengthAdjust="spacing" xml:space="preserve">${spans}</text>`,
  );
}

const file = `---
// Generated by scripts/build/portrait.mjs - edit that, not this file.
import { messages } from '@/i18n/messages';
import type { Locale } from '@/i18n/locales';
interface Props {
  locale: Locale;
}
const { about } = messages(Astro.props.locale);
---

<svg
  class="code-portrait"
  viewBox="0 0 ${(COLS * ADVANCE).toFixed(1)} ${((rows + 0.3) * LINE).toFixed(1)}"
  role="img"
  aria-label={about.portraitAlt}
  font-size="${EM}"
>
${rowsOut.join('\n')}
</svg>
`;

const target = path.join(root, 'src/modules/home/code-portrait.astro');
await writeFile(target, file);
console.log(
  `${path.relative(process.cwd(), target)} (${COLS}x${rows} cells, ${stream.length} glyphs of source)`,
);
